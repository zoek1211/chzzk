package kr.devcourse.chzzk;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.web.context.WebApplicationContext;

/** 2단계 데이터 파일(NOT NULL 송출 키 해시 열이 남은 live 테이블)로 시작해도 새 라이브를 시작할 수 있다. */
class LegacyLiveSchemaTest {

    @TempDir
    Path dataDir;

    @Test
    void 옛_송출_키_해시_열이_남은_데이터_파일에서도_라이브를_시작할_수_있다() throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:file:" + dataDir + "/chzzk", "sa", "");
             Statement s = c.createStatement()) {
            s.execute("CREATE TABLE live_broadcast (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "broadcast_key_hash VARCHAR(255) NOT NULL)");
        }

        try (ConfigurableApplicationContext app = new SpringApplicationBuilder(ChzzkApplication.class)
                .run("--chzzk.data-dir=" + dataDir, "--server.port=0")) {
            MockMvc mvc = TestWeb.mvc((WebApplicationContext) app);
            mvc.perform(post("/live").session(TestLogin.member(mvc)).contentType(MediaType.APPLICATION_JSON)
                            .content("{\"title\":\"옛 파일 위의 라이브\"}"))
                    .andExpect(status().isOk());
        }
    }
}
